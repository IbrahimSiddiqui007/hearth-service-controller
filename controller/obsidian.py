START = "<!-- psc:notes:start -->"
END = "<!-- psc:notes:end -->"


def service_note(service: dict, hosts: dict) -> str:
    host = hosts.get(service["host_id"], {})
    props = {"psc_id": service["id"], "type": "service", "runtime": service["runtime"],
             "host": service["host_id"], "tags": ["homelab"] + service.get("tags", []),
             "updated": service.get("updated_at", now())}
    parts = ["---", yaml.safe_dump(props, sort_keys=False, allow_unicode=True).strip(), "---", "",
             "# " + service["name"], "", service.get("description", ""), "",
             "<!-- psc:generated — edit the Owner notes section; other fields are managed by the controller. -->", "",
             "## At a glance", "",
             f"- Host: [[Host--{service['host_id']}|{host.get('name', service['host_id'])}]]",
             f"- Runtime: `{service['runtime']}`",
             f"- Last observed state: **{service.get('status', 'unknown')}**",
             f"- Observed at: {service.get('observed_at', 'Not observed')}", "", "## Access", ""]
    parts += ["- " + url for url in service.get("urls", [])] or ["No web URL recorded."]
    parts += ["", "Ports: " + (", ".join(service.get("ports", [])) or "None recorded"), "", "## Paths", ""]
    parts += ["- `" + path.replace("`", "") + "`" for path in service.get("paths", [])] or ["No paths recorded."]
    parts += ["", "## Dependencies", ""]
    parts += [f"- [[Service--{dep}]]" for dep in service.get("dependencies", [])] or ["None recorded."]
    parts += ["", "## Linked runtime components", ""]
    parts += [f"- [[Service--{member}]]" for member in service.get("component_ids", [])] or ["None recorded."]
    documentation = service.get('documentation', {})
    for key, title in (('installation', 'Installation notes'), ('backup_plan', 'Backup plan'), ('recovery', 'Recovery runbook')):
        parts += ['', '## ' + title, '', documentation.get(key) or 'No owner documentation recorded.']
    parts += ["", "## Credential pointers", ""]
    for credential in service.get("credentials", []):
        label = credential["label"]
        reference = credential.get("vault_ref", "")
        parts.append(f"- **{label}**" + (f" — {reference}" if reference else ""))
        if credential.get("username"):
            parts.append("  - Username: " + credential["username"])
        if credential.get("hint"):
            parts.append("  - Hint: " + credential["hint"])
    if not service.get("credentials"):
        parts.append("No vault references recorded. Secret values belong in your password manager.")
    parts += ["", "## Owner notes", "", START, service.get("notes", ""), END, ""]
    return redact("\n".join(parts))


def files_for_vault(store: Store) -> dict[str, str]:
    hosts = {x["id"]: x for x in store.all("hosts")}
    services = store.all("services")
    files = {}
    home = ["# Homelab", "", "Generated by Pi Service Controller. Open this folder as an Obsidian vault; no plugin required.", "",
            "Edit only the Owner notes section between its markers to sync notes back. Other fields are generated.", "",
            "## Hosts", ""]
    for host in hosts.values():
        home.append(f"- [[Host--{host['id']}|{host['name']}]]")
        props = yaml.safe_dump({"psc_id": host["id"], "type": "host", "os": host.get("os", "")}, sort_keys=False).strip()
        body = ["---", props, "---", "", "# " + host["name"], "", "OS: " + host.get("os", "Unknown"), "", "## Services", ""]
        body += [f"- [[Service--{s['id']}|{s['name']}]]" for s in services if s["host_id"] == host["id"]]
        files[f"Host--{host['id']}.md"] = "\n".join(body) + "\n"
    home += ["", "## Services", ""]
    for service in services:
        home.append(f"- [[Service--{service['id']}|{service['name']}]]")
        files[f"Service--{service['id']}.md"] = service_note(service, hosts)
    files["Home.md"] = "\n".join(home) + "\n"
    return files


def export_zip(store: Store) -> bytes:
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for filename, body in files_for_vault(store).items():
            archive.writestr("docs/" + filename, body)
        manifest = {"version": 1,
                    "hosts": [normalized(row, HostDefinition) for row in store.all("hosts")],
                    "services": [normalized(row, ServiceDefinition) for row in store.all("services")]}
        # Redact prose values, not serialized YAML: token_env is a reference, and
        # replacing a scalar with bare [REDACTED] would turn it into a YAML list.
        for service in manifest["services"]:
            for key in ("notes", "description"):
                service[key] = redact(service.get(key, ""))
        archive.writestr("lab.yaml", yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True))
    return output.getvalue()


def sync_vault(store: Store):
    """Only writes the dedicated vault beneath this workspace's data directory.

    Both-sided note changes conflict rather than overwriting. Unknown/external
    files, .obsidian settings, and note sections with damaged markers are preserved.
    """
    root = store.root / "obsidian"
    if root.is_symlink():
        raise ValueError("The managed vault cannot be a symlink")
    root.mkdir(exist_ok=True)
    state_path = store.root / "obsidian-state.json"
    if state_path.is_symlink():
        raise ValueError("The sync state cannot be a symlink")
    state = json.loads(state_path.read_text(encoding="utf-8")) if state_path.exists() else {}
    imported, written, conflicts = [], [], []
    for service in store.all("services"):
        sid = service["id"]
        path = root / f"Service--{sid}.md"
        if path.is_symlink():
            conflicts.append({"id": sid, "reason": "Symlink is not allowed"})
            continue
        if path.exists():
            if path.stat().st_size > 2_000_000:
                conflicts.append({"id": sid, "reason": "Note exceeds 2 MB"})
                continue
            text = path.read_text(encoding="utf-8")
            matches = re.findall(re.escape(START) + r"\n(.*?)\n" + re.escape(END), text, flags=re.DOTALL)
            if len(matches) != 1 or text.count(START) != 1 or text.count(END) != 1:
                conflicts.append({"id": sid, "reason": "Owner-note markers missing or duplicated"})
                continue
            local = matches[0]
            remote = service.get("notes", "")
            base = state.get(sid)
            if local != remote:
                if base is None or (local != base and remote != base):
                    conflicts.append({"id": sid, "reason": "Notes changed in both places, or no sync baseline exists"})
                    continue
                if local != base:
                    if len(local) > 100_000 or redact(local) != local:
                        conflicts.append({"id": sid, "reason": "Note too large or contains a recognized secret pattern"})
                        continue
                    with store.connection() as db:
                        db.execute("INSERT INTO note_history(service_id,ts,revision,notes) VALUES(?,?,?,?)",
                                   (sid, now(), service["revision"], remote))
                        service.update(notes=local, revision=service["revision"] + 1, updated_at=now())
                        store.put("services", service, db)
                        store.audit("obsidian.import", "success", "Owner notes updated from vault", sid, service["host_id"], db)
                    imported.append(sid)
        state[sid] = service.get("notes", "")
    blocked = {x["id"] for x in conflicts}
    for filename, body in files_for_vault(store).items():
        if filename.startswith("Service--") and filename[len("Service--"):-3] in blocked:
            continue
        path = root / filename
        if path.is_symlink():
            conflicts.append({"id": filename, "reason": "Symlink is not allowed"})
            continue
        # Do not replace unrelated pre-existing host/index files on first sync.
        if path.exists() and filename not in state.get("_generated_files", []) and not filename.startswith("Service--"):
            conflicts.append({"id": filename, "reason": "Existing file is not managed by this controller"})
            continue
        temporary = root / (filename + ".psc-tmp")
        if temporary.is_symlink():
            raise ValueError("Temporary sync path cannot be a symlink")
        temporary.write_text(body, encoding="utf-8")
        temporary.replace(path)
        written.append(filename)
    state["_generated_files"] = sorted(set(state.get("_generated_files", [])) | set(written))
    state_path.write_text(json.dumps(state, ensure_ascii=False, indent=2), encoding="utf-8")
    store.audit("obsidian.sync", "partial" if conflicts else "success", f"{len(written)} written; {len(imported)} imported; {len(conflicts)} conflicts")
    return {"path": str(root.resolve()), "written": len(written), "imported": imported, "conflicts": conflicts}
